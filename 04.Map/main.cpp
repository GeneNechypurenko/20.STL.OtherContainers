#include <iostream>
#include <string>
#include <map>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                      Контейнер map
==========================================================================================================================================

                                                           MAP
  map<K, V> — словник: зберігає пари «КЛЮЧ → ЗНАЧЕННЯ» і шукає значення за ключем, а не за номером.
  Ключі унікальні й автоматично відсортовані (усередині — збалансоване бінарне дерево пошуку), тому пошук швидкий
  навіть серед мільйонів елементів.
  Використовують для будь-якого пошуку за ключем: словник перекладів, телефонна книга, інвентар «назва → кількість»,
  налаштування «параметр → значення».

  ----------------------------------------------------------------------------------------------------------------------------------------

  Елемент map — пара:  first — ключ (змінювати не можна),  second — значення.

  Основні методи:
      m[key] = value;          додати або замінити значення
      m[key]                   доступ до значення; УВАГА: для відсутнього ключа СТВОРЮЄ елемент зі значенням за замовчуванням
      m.find(key)              ітератор на знайдений елемент або end()
      m.contains(key)          чи є ключ (C++20)
      m.erase(key)             видалити за ключем
      size()  empty()  clear()
  Обхід іде в порядку зростання ключів.
*/

// Англо-український словник
class Dictionary
{
private:
    map<string, string> words;                   // англійське слово → переклад

public:
    void add(const string& english, const string& ukrainian)
    {
        words[english] = ukrainian;              // нове слово або нове значення старого
    }

    void translate(const string& english) const
    {
        auto found = words.find(english);        // для перевірки — find, а не []
        if (found != words.end())
        {
            cout << english << " — " << found->second << endl;
        }
        else
        {
            cout << english << " — немає в словнику" << endl;
        }
    }

    void remove(const string& english)
    {
        words.erase(english);
    }

    void print() const
    {
        for (const pair<const string, string>& word : words)   // за абеткою ключів
        {
            cout << "  " << word.first << " — " << word.second << endl;
        }
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    Dictionary dictionary;
    dictionary.add("sword", "меч");
    dictionary.add("castle", "замок");
    dictionary.add("dragon", "дракон");
    dictionary.add("lock", "замок");             // значення можуть повторюватися — ключі ні
    dictionary.print();                          // castle, dragon, lock, sword — за абеткою

    dictionary.translate("dragon");
    dictionary.translate("wizard");

    dictionary.add("castle", "фортеця");         // той самий ключ — значення замінюється
    dictionary.remove("lock");
    dictionary.print();

    return 0;
}

