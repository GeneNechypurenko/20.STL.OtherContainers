#include <iostream>
#include <string>
#include <array>
#include <deque>
#include <queue>
#include <map>
#include <unordered_map>
#include <set>
#include <unordered_set>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                        Огляд інших контейнерів STL (для самостійного перегляду)
==========================================================================================================================================

  Ми розібрали основні контейнери vector, stack, queue, list і map. Тут коротко показано решту контейнерів: що це і навіщо.

  Що використовують у реальних проєктах:
      постійно   — vector (контейнер за замовчуванням)
      дуже часто — map, unordered_map, set, unordered_set, array
      часто      — queue, priority_queue, stack
      іноді      — deque
      рідко      — list (замість обирають vector), multimap, multiset

      ---------------------------------------------------------------------------------------------------------------------

                     Які відмінності між map, unordered_map, multimap, set, unordered_set, multiset?

            Контейнер           Зберігає            Порядок            Повтори          Швидкість пошуку            []
               map     	    ключ → значення	     відсортовано	         ні	            швидко (дерево)	             є
          unordered_map	    ключ → значення	         немає	             ні	            найшвидше (хеш)	             є
             multimap	    ключ → значення	     відсортовано	         так	        швидко (дерево)	           немає
               set	            значення	     відсортовано	         ні	            швидко (дерево)	           немає
          unordered_set	        значення	         немає	             ні	            найшвидше (хеш)	           немає
             multiset	        значення	     відсортовано	         так	        швидко (дерево)	           немає

                Усі шість — це варіації однієї ідеї, щоб обрати потрібний клас треба відповісти на три питання:
                1.  Що зберігаємо? Пари «ключ → значення» (map) чи лише значення (set).
                2.  Чи потрібен порядок? Відсортовано (дерево) чи без порядку, але швидше (хеш-таблиця, unordered_).
                3.  Чи можуть повторюватися ключі? Унікальні чи з повторами (multi).

          * Хеш-таблиця — це структура даних, яка знаходить елемент за ключем майже миттєво, без перебору і без дерева.
     
     ----------------------------------------------------------------------------------------------------------------------

*/

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // =====================================================================================================================
    // array<T, N> — масив ФІКСОВАНОГО розміру. Сучасна заміна звичайного масиву int arr[5]:
    // знає свій розмір, має at() з перевіркою, працює з циклом по діапазону та алгоритмами STL.
    // Навіщо: коли кількість елементів відома заздалегідь і не змінюється (7 днів тижня, 4 сторони світу).
    cout << "--- array ---" << endl;
    array<int, 7> stepsPerDay = { 8000, 12000, 5000, 9500, 11000, 15000, 7000 };
    cout << "Днів: " << stepsPerDay.size() << ", у середу: " << stepsPerDay.at(2) << endl;

    // =====================================================================================================================
    // priority_queue<T> — черга з пріоритетом: першим виходить НАЙБІЛЬШИЙ елемент, а не той, що прийшов першим.
    // Навіщо: обробка найважливішого завдання першим, пошук шляху в іграх, планувальники.
    cout << "--- priority_queue ---" << endl;
    priority_queue<int> urgency;                                // число — терміновість заявки в техпідтримку
    urgency.push(3);
    urgency.push(10);
    urgency.push(1);
    urgency.push(7);
    while (!urgency.empty())
    {
        cout << "Обробляємо заявку з терміновістю " << urgency.top() << endl;   // 10, 7, 3, 1
        urgency.pop();
    }

    // =====================================================================================================================
    // deque<T> — «двостороння черга»: як vector, але швидко додає і видаляє елементи з ОБОХ кінців.
    // Навіщо: саме на ньому «під капотом» побудовані queue і stack; напряму — коли потрібні push_front і push_back разом.
    cout << "--- deque ---" << endl;
    deque<string> recentFiles = { "main.cpp", "notes.txt" };
    recentFiles.push_front("report.docx");                      // щойно відкритий файл — на початок списку
    recentFiles.pop_back();                                     // найстаріший — геть зі списку
    for (const string& file : recentFiles)
    {
        cout << file << " ";
    }
    cout << endl;

    // =====================================================================================================================
    // unordered_map<K, V> — такий самий словник, як map, з тими самими методами, але ключі НЕ впорядковані
    // (усередині — хеш-таблиця), зате пошук ще швидший. У сучасному коді це найуживаніший словник;
    // map беруть, коли потрібен порядок ключів.
    // Навіщо: кеші, пошук за ID, підрахунки — усе, де порядок не важливий.
    cout << "--- unordered_map ---" << endl;
    unordered_map<string, int> votes;
    votes["Шахи"]++;
    votes["Дизайн"]++;
    votes["Шахи"]++;
    cout << "Голосів за шахи: " << votes["Шахи"] << ", варіантів: " << votes.size() << endl;

    // =====================================================================================================================
    // set<T> — множина: лише УНІКАЛЬНІ значення, повтор не додається; значення відсортовані.
    // unordered_set<T> — те саме без порядку і швидше.
    // Навіщо: прибрати повтори, швидко перевірити «чи вже було?» (відвідані локації, зареєстровані email).
    cout << "--- set / unordered_set ---" << endl;
    set<string> cities = { "Київ", "Львів", "Київ", "Одеса", "Львів" };
    cout << "Різних міст: " << cities.size() << endl;          // 3
    unordered_set<string> registered;
    cout << "Перша реєстрація: " << registered.insert("olena@gmail.com").second << endl;   // 1 — додано
    cout << "Повторна:         " << registered.insert("olena@gmail.com").second << endl;   // 0 — вже є

    // =====================================================================================================================
    // multimap<K, V> — як map, але один ключ може мати КІЛЬКА значень. Оператора [] немає.
    // Навіщо: події за датами, студенти за факультативами. Часто замість нього пишуть map<K, vector<V>>.
    cout << "--- multimap ---" << endl;
    multimap<string, string> clubs;
    clubs.insert({ "Шахи", "Олена" });
    clubs.insert({ "Дизайн", "Софія" });
    clubs.insert({ "Шахи", "Ігор" });
    auto range = clubs.equal_range("Шахи");                     // усі записи з ключем «Шахи»
    for (auto r = range.first; r != range.second; ++r)
    {
        cout << "Шахи: " << r->second << endl;
    }

    // =====================================================================================================================
    // multiset<T> — як set, але значення можуть ПОВТОРЮВАТИСЯ; зберігаються відсортованими.
    // Навіщо: відсортований набір з повторами — наприклад, оцінки, щоб швидко знати мінімальну й максимальну.
    cout << "--- multiset ---" << endl;
    multiset<int> grades = { 10, 7, 12, 7, 9 };
    cout << "Оцінок: " << grades.size() << ", сімок: " << grades.count(7)
        << ", найнижча: " << *grades.begin() << ", найвища: " << *grades.rbegin() << endl;

    return 0;
}
