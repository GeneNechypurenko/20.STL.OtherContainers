#include <iostream>
#include <string>
#include <queue>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                      Контейнер queue
==========================================================================================================================================

                                                         QUEUE
  queue<T> — черга: структура даних за принципом FIFO (First In — First Out): перший доданий елемент виходить першим.
  Додають у кінець черги, забирають з початку.
  Використовують там, де завдання обробляються в порядку надходження: черга друку, повідомлень,
  замовлень, гравців на матч.

  ----------------------------------------------------------------------------------------------------------------------------------------

  Основні методи:
      push(x)       стати в кінець черги
      front()       перший у черзі (не забирає його)
      back()        останній у черзі
      pop()         прибрати першого (нічого не повертає)
      size()  empty()
  front() і pop() для порожньої черги — помилка, тому перед ними перевіряють empty().
  Ітераторів і доступу за номером немає.
*/

// Принтер: документи друкуються в порядку надходження
class Printer
{
private:
    queue<string> jobs;

public:
    void addJob(const string& document)
    {
        jobs.push(document);
        cout << "У черзі: " << document << " (документів: " << jobs.size() << ")" << endl;
    }

    void printNext()
    {
        if (jobs.empty())
        {
            cout << "Черга порожня" << endl;
            return;
        }
        cout << "Друкується: " << jobs.front() << endl;
        jobs.pop();
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    Printer printer;
    printer.addJob("звіт.pdf");
    printer.addJob("фото.jpg");
    printer.addJob("резюме.docx");

    printer.printNext();                         // звіт.pdf — він прийшов першим
    printer.printNext();
    printer.addJob("квиток.pdf");                // новий документ стає в КІНЕЦЬ черги
    printer.printNext();
    printer.printNext();
    printer.printNext();                         // Черга порожня

    return 0;
}

