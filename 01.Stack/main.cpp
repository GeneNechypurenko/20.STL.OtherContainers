#include <iostream>
#include <string>
#include <stack>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                      Контейнер stack
==========================================================================================================================================

                                                         STACK
  stack<T> — повнісю відповідає структурі данних стек: останній доданий елемент виходить першим;
  додавати, дивитися і забирати можна лише ВЕРХНІЙ елемент.
  Використовують для історії дій: кнопка «Скасувати» (Ctrl+Z), кнопка «Назад» у браузері, повернення з викликів функцій.

  ----------------------------------------------------------------------------------------------------------------------------------------

  Основні методи:
      push(x)       покласти на верх
      top()         верхній елемент (не забирає його)
      pop()         прибрати верхній елемент (нічого не повертає)
      size()  empty()
  top() і pop() для порожнього стека — помилка (невизначена поведінка), тому перед ними перевіряють empty().
  Ітераторів і доступу за номером немає.
*/

// Текстовий редактор з кнопкою «Скасувати»
class TextEditor
{
private:
    string text;
    stack<string> history;                       // попередні версії тексту

public:
    void type(const string& words)
    {
        history.push(text);                      // запам'ятовуємо стан ДО зміни
        text += words;
    }

    void undo()
    {
        if (history.empty())
        {
            cout << "Нічого скасовувати" << endl;
            return;
        }
        text = history.top();                    // повертаємо останній збережений стан
        history.pop();
    }

    void print() const
    {
        cout << "Текст: \"" << text << "\"" << endl;
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    TextEditor editor;
    editor.type("Привіт");
    editor.type(", світ");
    editor.type("!!!");
    editor.print();                              // Привіт, світ!!!

    editor.undo();                               // Ctrl+Z
    editor.print();                              // Привіт, світ
    editor.undo();
    editor.print();                              // Привіт
    editor.undo();
    editor.undo();                               // Нічого скасовувати

    return 0;
}

